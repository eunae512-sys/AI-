// ──────────────────────────────────────────────
// 5) 슬롯 치환 — {menu} {city} {brand} {district} {industryShort}
// ──────────────────────────────────────────────
export function fillSlots(template: string, slots: Record<string, string | undefined>): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => {
    const v = slots[key];
    if (!v) return "";
    return v;
  }).replace(/\s+/g, " ").replace(/\s+([,.·])/g, "$1").trim();
}

// 빈 슬롯 후크 자동 제거 — "{menu}" 가 비어서 ", " 가 남거나 단어 사이 공백 어색하면 폐기
export function isClean(text: string): boolean {
  if (!text || text.length < 6) return false;
  if (/\{[^}]+\}/.test(text)) return false; // 치환 안된 슬롯 남음
  if (/^\s*[—·,.]/.test(text)) return false; // 구두점으로 시작
  if (/\s{2,}/.test(text)) return false;
  return true;
}
